from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any

try:
    from .common import atomic_write
except ImportError:
    from common import atomic_write


def load(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or not isinstance(value.get("records"), list):
        raise TypeError(f"{path} must contain a protocol dataset")
    return value


def identifier(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value)


def literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def write_protocol(path: Path, declaration: str, type_name: str, value: Any) -> None:
    content = (
        "// This file is auto-generated by proper-data/crawler/"
        "generate_historical_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        f'import type {{ {type_name} }} from "../../types";\n\n'
        f"export const {declaration} = {literal(value)} satisfies readonly "
        f"{type_name}[];\n"
    )
    atomic_write(path, content.encode("utf-8"))


def source(raw: dict[str, Any], source_type: int) -> dict[str, Any]:
    result = {
        "url": raw["official_url"],
        "sha256": raw["sha256"],
        "sourceReportType": source_type,
        "derivation": raw.get("derivation", "extracted-tic-column"),
    }
    for source_key, output_key in (
        ("retrieved_at", "retrievedAt"),
        ("final_url", "finalUrl"),
        ("provenance", "provenance"),
    ):
        if raw.get(source_key) is not None:
            result[output_key] = raw[source_key]
    return result


def ballot_name(dataset: dict[str, Any], contest: str) -> str:
    if contest == "party":
        return "party"
    return (
        "presidential"
        if str(dataset["election"]).endswith("-president")
        else "single-member"
    )


def uik_value(
    dataset: dict[str, Any],
    record: dict[str, Any],
    tik_sources: dict[str, dict[str, Any]],
    contest: str,
) -> dict[str, Any]:
    types = dataset["contests"][contest]
    direct_source = record.get(f"{contest}_source")
    return {
        "election": dataset["election"],
        "level": "uik",
        "reportType": int(types["uik"]),
        "ballot": ballot_name(dataset, contest),
        "uikNumber": record["uik_number"],
        "uikTvd": str(record["uik_tvd"]),
        "tikTvd": str(record["tik_tvd"]),
        "tikName": record["tik_name"],
        "accounting": record[f"{contest}_accounting"],
        "votes": record[f"{contest}_votes"],
        "source": source(
            direct_source or tik_sources[record["tik_tvd"]][contest],
            int(direct_source["report_type"] if direct_source else types["tic"]),
        ),
    }


def tik_value(
    dataset: dict[str, Any],
    tik_tvd: str,
    tik_sources: dict[str, dict[str, Any]],
    official: dict[str, dict[str, Any]],
    contest: str,
) -> dict[str, Any]:
    types = dataset["contests"][contest]
    aggregate = official[tik_tvd][contest]
    return {
        "election": dataset["election"],
        "level": "tic",
        "reportType": int(types["tic"]),
        "ballot": ballot_name(dataset, contest),
        "tikTvd": tik_tvd,
        "tikName": tik_sources[tik_tvd].get("tik_name", ""),
        "uikCount": aggregate["uik_count"],
        "accounting": aggregate["accounting"],
        "votes": aggregate["votes"],
        "uikTvds": aggregate["uik_tvds"],
        "source": source(
            tik_sources[tik_tvd][contest],
            int(tik_sources[tik_tvd][contest].get("report_type", types["tic"])),
        ),
    }


def clean(roots: list[Path], expected: set[Path]) -> None:
    for root in roots:
        for path in root.glob("*.ts"):
            if path not in expected:
                path.unlink()


def write_types(dataset: dict[str, Any], output: Path) -> None:
    tic_types = " | ".join(str(value["tic"]) for value in dataset["contests"].values())
    uik_types = " | ".join(str(value["uik"]) for value in dataset["contests"].values())
    all_types = " | ".join(
        str(report_type)
        for value in dataset["contests"].values()
        for report_type in (value["tic"], value["uik"])
    )
    ballots = " | ".join(
        f'"{ballot_name(dataset, contest)}"' for contest in dataset["contests"]
    )
    content = f'''// Generated protocol files use these structural contracts. No database is involved.

export type VoteMap = Readonly<Record<string, number>>;

export type ProtocolSource = Readonly<{{
  url: string;
  sha256: string;
  sourceReportType: {all_types};
  derivation: "direct" | "extracted-tic-column";
  retrievedAt?: string;
  finalUrl?: string;
  provenance?: "live-official" | "wayback";
}}>;

export type UikProtocol = Readonly<{{
  election: "{dataset["election"]}";
  level: "uik";
  reportType: {uik_types};
  ballot: {ballots};
  uikNumber: number;
  uikTvd: string;
  tikTvd: string;
  tikName: string;
  accounting: VoteMap;
  votes: VoteMap;
  source: ProtocolSource;
}}>;

export type TicProtocol = Readonly<{{
  election: "{dataset["election"]}";
  level: "tic";
  reportType: {tic_types};
  ballot: {ballots};
  tikTvd: string;
  tikName: string;
  uikCount: number;
  accounting: VoteMap;
  votes: VoteMap;
  uikTvds: readonly string[];
  source: ProtocolSource;
}}>;

export type UikTikRelation = Readonly<{{
  uikNumber: number;
  uikTvd: string;
  tikTvd: string;
  tikName: string;
}}>;
'''
    atomic_write(output / "protocol" / "types.ts", content.encode("utf-8"))


def generate(
    dataset: dict[str, Any], output: Path, shard_size: int = 250
) -> dict[str, int]:
    if shard_size < 1:
        raise ValueError("shard-size must be positive")
    records = sorted(
        dataset["records"],
        key=lambda item: (
            str(item.get("region", "")),
            str(item["tik_tvd"]),
            int(item["uik_number"]),
        ),
    )
    tik_sources = {str(item["tik_tvd"]): item for item in dataset["sources"]}
    official = {str(item["tik_tvd"]): item for item in dataset["tik_protocols"]}
    records_by_region: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    tiks_by_region: defaultdict[str, set[str]] = defaultdict(set)
    for record in records:
        region = str(record.get("region", "unknown"))
        records_by_region[region].append(record)
        tiks_by_region[region].add(str(record["tik_tvd"]))

    expected: set[Path] = set()
    roots: list[Path] = []
    year, election_kind = dataset["election"].split("-", 1)
    declaration_prefix = identifier(f"{election_kind}_{year}")
    for region in sorted(
        records_by_region,
        key=lambda value: (int(value) if value.isdigit() else 999, value),
    ):
        for contest, types in dataset["contests"].items():
            uik_root = output / "protocol" / "uik" / str(types["uik"])
            tic_root = output / "protocol" / "tic" / str(types["tic"])
            roots.extend((uik_root, tic_root))
            contest_records = [
                record
                for record in records_by_region[region]
                if f"{contest}_accounting" in record and f"{contest}_votes" in record
            ]
            for part, start in enumerate(range(0, len(contest_records), shard_size), 1):
                path = uik_root / f"region-{region}-part-{part:03d}.ts"
                expected.add(path)
                write_protocol(
                    path,
                    identifier(
                        f"{declaration_prefix}_uik_{types['uik']}_region_{region}_part_{part:03d}"
                    ),
                    "UikProtocol",
                    [
                        uik_value(dataset, record, tik_sources, contest)
                        for record in contest_records[start : start + shard_size]
                    ],
                )
            path = tic_root / f"region-{region}.ts"
            expected.add(path)
            write_protocol(
                path,
                identifier(
                    f"{declaration_prefix}_tic_{types['tic']}_region_{region}"
                ),
                "TicProtocol",
                [
                    tik_value(dataset, tik_tvd, tik_sources, official, contest)
                    for tik_tvd in sorted(tiks_by_region[region])
                ],
            )

    relation_groups: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for relation in dataset["relations"]:
        relation_groups[str(relation.get("region", "unknown"))].append(relation)
    relation_root = output / "uik-to-tik"
    relation_expected: set[Path] = set()
    imports: list[str] = []
    names: list[str] = []
    for region in sorted(
        relation_groups,
        key=lambda value: (int(value) if value.isdigit() else 999, value),
    ):
        name = identifier(f"{declaration_prefix}_uik_to_tik_region_{region}")
        names.append(name)
        path = relation_root / f"region-{region}.ts"
        relation_expected.add(path)
        values = [
            {
                "uikNumber": item["uik_number"],
                "uikTvd": str(item["uik_tvd"]),
                "tikTvd": str(item["tik_tvd"]),
                "tikName": item["tik_name"],
            }
            for item in sorted(
                relation_groups[region],
                key=lambda item: (int(item["uik_number"]), str(item["uik_tvd"])),
            )
        ]
        content = (
            "// This file is auto-generated by proper-data/crawler/"
            "generate_historical_typescript.py.\n"
            "// Do not edit it manually.\n\n"
            'import type { UikTikRelation } from "../protocol/types";\n\n'
            f"export const {name} = {literal(values)} satisfies readonly "
            "UikTikRelation[];\n"
        )
        atomic_write(path, content.encode("utf-8"))
        imports.append(f'import {{ {name} }} from "./uik-to-tik/region-{region}";')
    relation_content = (
        "// This file is auto-generated by proper-data/crawler/"
        "generate_historical_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        'import type { UikTikRelation } from "./protocol/types";\n'
        + "\n".join(imports)
        + f"\n\nexport const {declaration_prefix}_uik_to_tik = [\n  ..."
        + ",\n  ...".join(names)
        + "\n] satisfies readonly UikTikRelation[];\n"
    )
    atomic_write(output / "uik-to-tik.ts", relation_content.encode("utf-8"))
    write_types(dataset, output)
    roots.extend(
        path
        for level in (output / "protocol" / "tic", output / "protocol" / "uik")
        if level.is_dir()
        for path in level.iterdir()
        if path.is_dir()
    )
    clean(list(set(roots)), expected)
    clean([relation_root], relation_expected)
    return {
        "uiks": len(records),
        "tics": len(tik_sources),
        "protocol_shards": len(expected),
        "relation_shards": len(relation_expected),
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate sharded historical election TypeScript protocols"
    )
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--shard-size", type=int, default=250)
    args = parser.parse_args()
    print(
        json.dumps(generate(load(args.dataset), args.output, args.shard_size), indent=2)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
