from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any


def _load(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or not isinstance(value.get("records"), list):
        raise TypeError(f"{path} must contain a protocol dataset object")
    return value


def _identifier(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value)


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def _write_protocol(path: Path, declaration: str, type_name: str, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        f'import type {{ {type_name} }} from "../../types";\n\n'
        f"export const {declaration} = {_literal(value)} satisfies {type_name};\n"
    )
    path.write_text(content, encoding="utf-8")


def _source(raw: dict[str, Any], report_type: int) -> dict[str, Any]:
    return {
        "url": raw["official_url"],
        "sha256": raw["sha256"],
        "sourceReportType": report_type,
    }


def _sum_maps(records: list[dict[str, Any]], field: str) -> dict[str, int]:
    totals: defaultdict[str, int] = defaultdict(int)
    for record in records:
        for name, value in record[field].items():
            totals[name] += int(value)
    return dict(totals)


def generate(dataset: dict[str, Any], output: Path) -> dict[str, int]:
    protocol_root = output / "protocol"
    records = dataset["records"]
    sources = {item["tik_tvd"]: item for item in dataset["sources"]}
    grouped: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        grouped[record["tik_tvd"]].append(record)

    expected: set[Path] = set()
    for record in records:
        for report_type, ballot, accounting_field, vote_field, source_key in (
            (242, "party", "party_accounting", "party_votes", "party"),
            (463, "single-member", "candidate_accounting", "candidate_votes", "candidate"),
        ):
            uik_tvd = str(record["uik_tvd"])
            path = protocol_root / "uik" / str(report_type) / f"{uik_tvd}.ts"
            expected.add(path)
            value = {
                "election": "2021-duma",
                "level": "uik",
                "reportType": report_type,
                "ballot": ballot,
                "uikNumber": record["uik_number"],
                "uikTvd": uik_tvd,
                "tikTvd": record["tik_tvd"],
                "tikName": record["tik_name"],
                "accounting": record[accounting_field],
                "votes": record[vote_field],
                "source": _source(sources[record["tik_tvd"]][source_key], 233 if report_type == 242 else 464),
            }
            declaration = _identifier(f"duma_2021_uik_{report_type}_{uik_tvd}")
            _write_protocol(path, declaration, "UikProtocol", value)

    for tik_tvd, tik_records in grouped.items():
        for report_type, ballot, accounting_field, vote_field, source_key in (
            (233, "party", "party_accounting", "party_votes", "party"),
            (464, "single-member", "candidate_accounting", "candidate_votes", "candidate"),
        ):
            path = protocol_root / "tic" / str(report_type) / f"{tik_tvd}.ts"
            expected.add(path)
            value = {
                "election": "2021-duma",
                "level": "tic",
                "reportType": report_type,
                "ballot": ballot,
                "tikTvd": tik_tvd,
                "tikName": tik_records[0]["tik_name"],
                "uikCount": len(tik_records),
                "accounting": _sum_maps(tik_records, accounting_field),
                "votes": _sum_maps(tik_records, vote_field),
                "uikTvds": [str(record["uik_tvd"]) for record in tik_records],
                "source": _source(sources[tik_tvd][source_key], report_type),
            }
            declaration = _identifier(f"duma_2021_tic_{report_type}_{tik_tvd}")
            _write_protocol(path, declaration, "TicProtocol", value)

    relation_path = output / "uik-to-tik.ts"
    relations = [
        {
            "uikNumber": record["uik_number"],
            "uikTvd": str(record["uik_tvd"]),
            "tikTvd": record["tik_tvd"],
            "tikName": record["tik_name"],
        }
        for record in records
    ]
    relation_path.write_text(
        "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        'import type { UikTikRelation } from "./protocol/types";\n\n'
        f"export const duma_2021_uik_to_tik = {_literal(relations)} "
        "satisfies readonly UikTikRelation[];\n",
        encoding="utf-8",
    )

    generated_roots = [
        protocol_root / "uik" / "242",
        protocol_root / "uik" / "463",
        protocol_root / "tic" / "233",
        protocol_root / "tic" / "464",
    ]
    for root in generated_roots:
        for path in root.glob("*.ts"):
            if path not in expected:
                path.unlink()
    return {"uiks": len(records), "tics": len(grouped), "protocol_files": len(expected)}


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate file-first TypeScript protocols")
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = generate(_load(args.dataset), args.output)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
