from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any

try:
    from .common import atomic_write
except ImportError:
    from common import atomic_write


def _load(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or not isinstance(value.get("records"), list):
        raise TypeError(f"{path} must contain a protocol dataset object")
    return value


def _identifier(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value)


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def _write_protocol(
    path: Path,
    declaration: str,
    type_name: str,
    value: Any,
    *,
    collection: bool = False,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        f'import type {{ {type_name} }} from "../../types";\n\n'
        f"export const {declaration} = {_literal(value)} satisfies "
        f"{'readonly ' if collection else ''}{type_name}{'[]' if collection else ''};\n"
    )
    atomic_write(path, content.encode("utf-8"))


def _source(raw: dict[str, Any], report_type: int) -> dict[str, Any]:
    result = {
        "url": raw["official_url"],
        "sha256": raw["sha256"],
        "sourceReportType": report_type,
        "derivation": "direct" if report_type in (242, 463) else "extracted-tic-column",
    }
    for source_key, output_key in (
        ("retrieved_at", "retrievedAt"),
        ("final_url", "finalUrl"),
        ("provenance", "provenance"),
    ):
        if raw.get(source_key) is not None:
            result[output_key] = raw[source_key]
    return result


def _sum_maps(records: list[dict[str, Any]], field: str) -> dict[str, int]:
    totals: defaultdict[str, int] = defaultdict(int)
    for record in records:
        for name, value in record[field].items():
            totals[name] += int(value)
    return dict(totals)


def _uik_value(
    record: dict[str, Any],
    sources: dict[str, dict[str, Any]],
    report_type: int,
) -> dict[str, Any]:
    party = report_type == 242
    source_key = "party" if party else "candidate"
    accounting_field = f"{source_key}_accounting"
    vote_field = f"{source_key}_votes"
    return {
        "election": "2021-duma",
        "level": "uik",
        "reportType": report_type,
        "ballot": "party" if party else "single-member",
        "uikNumber": record["uik_number"],
        "uikTvd": str(record["uik_tvd"]),
        "tikTvd": record["tik_tvd"],
        "tikName": record["tik_name"],
        "accounting": record[accounting_field],
        "votes": record[vote_field],
        "source": _source(
            record.get(f"{source_key}_source")
            or sources[record["tik_tvd"]][source_key],
            report_type
            if record.get(f"{source_key}_source")
            else (233 if party else 464),
        ),
    }


def _tik_value(
    tik_tvd: str,
    tik_records: list[dict[str, Any]],
    sources: dict[str, dict[str, Any]],
    official: dict[str, dict[str, Any]],
    report_type: int,
) -> dict[str, Any]:
    party = report_type == 233
    source_key = "party" if party else "candidate"
    accounting_field = f"{source_key}_accounting"
    vote_field = f"{source_key}_votes"
    aggregate = official.get(tik_tvd, {}).get(source_key)
    if aggregate is None:
        aggregate = {
            "accounting": _sum_maps(tik_records, accounting_field),
            "votes": _sum_maps(tik_records, vote_field),
            "uik_count": len(tik_records),
            "uik_tvds": [str(record["uik_tvd"]) for record in tik_records],
        }
    return {
        "election": "2021-duma",
        "level": "tic",
        "reportType": report_type,
        "ballot": "party" if party else "single-member",
        "tikTvd": tik_tvd,
        "tikName": sources[tik_tvd].get("tik_name", tik_records[0]["tik_name"]),
        "uikCount": aggregate["uik_count"],
        "accounting": aggregate["accounting"],
        "votes": aggregate["votes"],
        "uikTvds": aggregate["uik_tvds"],
        "source": _source(sources[tik_tvd][source_key], report_type),
    }


def _clean_generated(roots: list[Path], expected: set[Path]) -> None:
    for root in roots:
        for path in root.glob("*.ts"):
            if path not in expected:
                path.unlink()


def generate(
    dataset: dict[str, Any],
    output: Path,
    *,
    shard_by_region: bool = False,
    shard_size: int = 250,
) -> dict[str, int]:
    if shard_size < 1:
        raise ValueError("shard_size must be positive")
    protocol_root = output / "protocol"
    records = sorted(
        dataset["records"],
        key=lambda item: (
            str(item["tik_tvd"]),
            int(item["uik_number"]),
            str(item["uik_tvd"]),
        ),
    )
    sources = {item["tik_tvd"]: item for item in dataset["sources"]}
    official = {item["tik_tvd"]: item for item in dataset.get("tik_protocols", [])}
    grouped: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        grouped[record["tik_tvd"]].append(record)

    if shard_by_region:
        return _generate_region_shards(
            dataset, output, records, sources, grouped, official, shard_size
        )

    expected: set[Path] = set()
    for record in records:
        for report_type, ballot, accounting_field, vote_field, source_key in (
            (242, "party", "party_accounting", "party_votes", "party"),
            (
                463,
                "single-member",
                "candidate_accounting",
                "candidate_votes",
                "candidate",
            ),
        ):
            if accounting_field not in record or vote_field not in record:
                continue
            uik_tvd = str(record["uik_tvd"])
            path = protocol_root / "uik" / str(report_type) / f"{uik_tvd}.ts"
            expected.add(path)
            value = _uik_value(record, sources, report_type)
            declaration = _identifier(f"duma_2021_uik_{report_type}_{uik_tvd}")
            _write_protocol(path, declaration, "UikProtocol", value)

    for tik_tvd, tik_records in grouped.items():
        for report_type, ballot, accounting_field, vote_field, source_key in (
            (233, "party", "party_accounting", "party_votes", "party"),
            (
                464,
                "single-member",
                "candidate_accounting",
                "candidate_votes",
                "candidate",
            ),
        ):
            path = protocol_root / "tic" / str(report_type) / f"{tik_tvd}.ts"
            expected.add(path)
            value = _tik_value(
                tik_tvd, tik_records, sources, official, report_type
            )
            declaration = _identifier(f"duma_2021_tic_{report_type}_{tik_tvd}")
            _write_protocol(path, declaration, "TicProtocol", value)

    relation_path = output / "uik-to-tik.ts"
    relations = [
        {
            "uikNumber": record["uik_number"],
            "uikTvd": str(record["uik_tvd"]),
            "tikTvd": record["tik_tvd"],
            "tikName": record["tik_name"],
        }
        for record in records
    ]
    relation_content = (
        "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        'import type { UikTikRelation } from "./protocol/types";\n\n'
        f"export const duma_2021_uik_to_tik = {_literal(relations)} "
        "satisfies readonly UikTikRelation[];\n"
    )
    atomic_write(relation_path, relation_content.encode("utf-8"))

    generated_roots = [
        protocol_root / "uik" / "242",
        protocol_root / "uik" / "463",
        protocol_root / "tic" / "233",
        protocol_root / "tic" / "464",
    ]
    _clean_generated(generated_roots, expected)
    return {"uiks": len(records), "tics": len(grouped), "protocol_files": len(expected)}


def _generate_region_shards(
    dataset: dict[str, Any],
    output: Path,
    records: list[dict[str, Any]],
    sources: dict[str, dict[str, Any]],
    grouped: dict[str, list[dict[str, Any]]],
    official: dict[str, dict[str, Any]],
    shard_size: int,
) -> dict[str, int]:
    protocol_root = output / "protocol"
    records_by_region: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        records_by_region[str(record.get("region", "unknown"))].append(record)
    tiks_by_region: defaultdict[str, list[str]] = defaultdict(list)
    for tik_tvd, source in sources.items():
        tiks_by_region[str(source.get("region", "unknown"))].append(tik_tvd)

    expected: set[Path] = set()
    for region in sorted(records_by_region, key=lambda value: (int(value) if value.isdigit() else 999, value)):
        region_records = records_by_region[region]
        for report_type in (242, 463):
            source_key = "party" if report_type == 242 else "candidate"
            region_ballot_records = [
                record
                for record in region_records
                if f"{source_key}_accounting" in record
                and f"{source_key}_votes" in record
            ]
            for part, start in enumerate(
                range(0, len(region_ballot_records), shard_size), 1
            ):
                path = (
                    protocol_root
                    / "uik"
                    / str(report_type)
                    / f"region-{region}-part-{part:03d}.ts"
                )
                expected.add(path)
                values = [
                    _uik_value(record, sources, report_type)
                    for record in region_ballot_records[start : start + shard_size]
                ]
                _write_protocol(
                    path,
                    _identifier(
                        f"duma_2021_uik_{report_type}_region_{region}_part_{part:03d}"
                    ),
                    "UikProtocol",
                    values,
                    collection=True,
                )
        for report_type in (233, 464):
            path = protocol_root / "tic" / str(report_type) / f"region-{region}.ts"
            expected.add(path)
            values = [
                _tik_value(tik_tvd, grouped[tik_tvd], sources, official, report_type)
                for tik_tvd in sorted(tiks_by_region[region])
            ]
            _write_protocol(
                path,
                _identifier(f"duma_2021_tic_{report_type}_region_{region}"),
                "TicProtocol",
                values,
                collection=True,
            )

    relations = dataset.get("relations") or [
        {
            "uik_number": record["uik_number"],
            "uik_tvd": record["uik_tvd"],
            "tik_tvd": record["tik_tvd"],
            "tik_name": record["tik_name"],
            "region": record.get("region", "unknown"),
        }
        for record in records
    ]
    relation_root = output / "uik-to-tik"
    relation_expected: set[Path] = set()
    relation_groups: defaultdict[str, list[dict[str, Any]]] = defaultdict(list)
    for item in relations:
        relation_groups[str(item.get("region", "unknown"))].append(item)
    imports: list[str] = []
    names: list[str] = []
    for region in sorted(relation_groups, key=lambda value: (int(value) if value.isdigit() else 999, value)):
        name = _identifier(f"duma_2021_uik_to_tik_region_{region}")
        names.append(name)
        path = relation_root / f"region-{region}.ts"
        relation_expected.add(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        values = [
            {
                "uikNumber": item["uik_number"],
                "uikTvd": str(item["uik_tvd"]),
                "tikTvd": str(item["tik_tvd"]),
                "tikName": item["tik_name"],
            }
            for item in sorted(
                relation_groups[region],
                key=lambda value: (int(value["uik_number"]), str(value["uik_tvd"])),
            )
        ]
        content = (
            "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
            "// Do not edit it manually.\n\n"
            'import type { UikTikRelation } from "../protocol/types";\n\n'
            f"export const {name} = {_literal(values)} satisfies readonly UikTikRelation[];\n"
        )
        atomic_write(path, content.encode("utf-8"))
        imports.append(f'import {{ {name} }} from "./uik-to-tik/region-{region}";')
    relation_content = (
        "// This file is auto-generated by proper-data/crawler/generate_typescript.py.\n"
        "// Do not edit it manually.\n\n"
        'import type { UikTikRelation } from "./protocol/types";\n'
        + "\n".join(imports)
        + "\n\nexport const duma_2021_uik_to_tik = [\n  ..."
        + ",\n  ...".join(names)
        + "\n] satisfies readonly UikTikRelation[];\n"
    )
    atomic_write(output / "uik-to-tik.ts", relation_content.encode("utf-8"))

    roots = [
        protocol_root / "uik" / "242",
        protocol_root / "uik" / "463",
        protocol_root / "tic" / "233",
        protocol_root / "tic" / "464",
    ]
    _clean_generated(roots, expected)
    _clean_generated([relation_root], relation_expected)
    return {
        "uiks": len(records),
        "party_uiks": sum("party_accounting" in item for item in records),
        "candidate_uiks": sum("candidate_accounting" in item for item in records),
        "tics": len(grouped),
        "protocol_files": len(expected),
        "relation_shards": len(relation_expected),
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate file-first TypeScript protocols"
    )
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--shard-by-region", action="store_true")
    parser.add_argument("--shard-size", type=int, default=250)
    args = parser.parse_args()
    result = generate(
        _load(args.dataset),
        args.output,
        shard_by_region=args.shard_by_region,
        shard_size=args.shard_size,
    )
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
